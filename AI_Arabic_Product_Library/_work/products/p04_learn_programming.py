        ("promptbox", "أرسل هذا إلى Claude Code بعد أن تكتب محاولتك", review_prompt),
        ("h3", "تلميح إن تعثرت"),
        ("callout", "tip", "تلميح", [hint]),
        ("h3", "اختبر فهمك"),
        ("ol", test_questions),
        ("h3", "خطوة التحسين"),
